-- 추천 정렬·최소 궁합 조건 철회
--
-- 20260909120000 에서 넣었던 두 컬럼을 도로 뺀다. 궁합을 **조건**으로 만든 것이
-- 잘못이었다:
--
--   - 최소 궁합은 사주를 적지 않은 분(선택 입력이다)을 추천에서 통째로 지운다.
--     선택 항목이 사실상의 자격 요건이 된다.
--   - 정렬 선택지는 "궁합 낮은 순으로 보고 싶다"는 뜻이 없는 선택지다. 조건에
--     맞는 분들 안에서는 궁합이 높은 순이 언제나 맞는 순서다.
--
-- 그래서 궁합은 저장하는 조건이 아니라 **서버가 항상 적용하는 순서**가 된다.
-- 사용자가 정하는 것은 거리·나이·목적 같은 조건까지고, 그 안의 순서는
-- 서비스가 정한다 (PRD 8.4).
--
-- 우리 부모님 사주가 없으면 궁합을 낼 수 없으므로 최근 활동 순으로 돌아간다.
-- =============================================================================

