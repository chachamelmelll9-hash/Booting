-- 두 지점 사이 거리(km). 반경 필터가 서버에서 이 함수를 쓴다.
create or replace function public.region_distance_km(a text, b text)
returns double precision
language sql
stable
as $$
  select 6371 * acos(
    least(1.0, greatest(-1.0,
      cos(radians(ra.lat)) * cos(radians(rb.lat)) * cos(radians(rb.lng) - radians(ra.lng))
      + sin(radians(ra.lat)) * sin(radians(rb.lat))
    ))
  )
  from regions ra, regions rb
  where ra.code = a and rb.code = b;
$$;
