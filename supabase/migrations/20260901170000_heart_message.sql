-- =============================================================================
-- 관심(하트)에 인사말 첨부
--
-- 상호 하트가 되면 이 문장이 대화방의 첫 메시지로 옮겨간다. 처음 말을 트는
-- 부담이 대화 이탈의 가장 큰 이유인데, 이미 건넨 한마디가 남아 있으면
-- 빈 채팅방을 마주하지 않아도 된다.
--
-- 길이를 200자로 묶는 이유: 인사말이지 편지가 아니다. 길어지면 받은 관심
-- 목록이 읽기 어려워지고, 매칭 전 낯선 사람에게 보내는 글이라 짧을수록 안전하다.
-- =============================================================================

alter table hearts
  add column if not exists message text
  check (message is null or char_length(message) between 1 and 200);

comment on column hearts.message is
  '관심과 함께 보낸 인사말. 상호 하트 시 대화방 첫 메시지로 복사된다.';
